class TestNativeCeilings(unittest.TestCase):
    def budget(self):
        return event("budget_exceeded", budget="max_tokens", limit="max_tokens",
                     used=120000, max=100000, config_path="budget.max_tokens")

    def test_30_budget_exceeded_ends_the_run_deterministically(self):
        for status in (0, 1, 137, None):
            with self.subTest(exit_status=status):
                result = events.analyze(stream(call("a", "Bash", {"command": "make"}),
                                               self.budget()), exit_status=status)
                self.assertEqual(result.stream, events.COMPLETE)
                self.assertEqual(result.agent_exit, events.NORMAL)
                self.assertEqual(result.limit_reached, events.NATIVE_CEILING)
                self.assertEqual(result.native_ceiling["event"], "budget_exceeded")
                self.assertEqual(result.native_ceiling["config_path"], "budget.max_tokens")
                self.assertEqual(result.native_ceiling["used"], "120000")
                self.assertEqual(result.native_ceiling["max"], "100000")

    def test_31_a_ceiling_works_without_a_terminal_event(self):
        result = events.analyze(stream(self.budget(), terminal=False), exit_status=1)
        self.assertEqual(result.stream, events.COMPLETE)
        self.assertEqual(result.limit_reached, events.NATIVE_CEILING)

    def test_32_max_iterations_reached_records_its_derived_config_path(self):
        result = events.analyze(
            stream(event("max_iterations_reached", max_iterations=40)), exit_status=0)
        self.assertEqual(result.limit_reached, events.NATIVE_CEILING)
        self.assertEqual(result.native_ceiling,
                         {"event": "max_iterations_reached",
                          "config_path": "agents.root.max_iterations",
                          "max_iterations": 40})

    def test_33_an_error_event_with_code_loop_detected_is_a_ceiling(self):
        result = events.analyze(stream(event("error", code="loop_detected",
                                             message="too many consecutive tool calls")),
                                exit_status=0)
        self.assertEqual(result.limit_reached, events.NATIVE_CEILING)
        self.assertEqual(result.native_ceiling["event"], "loop_detected")
        self.assertIn("max_consecutive_tool_calls", result.native_ceiling["config_path"])

    def test_34_an_error_event_with_another_code_is_not_a_ceiling(self):
        result = events.analyze(stream(event("error", code="model_unavailable")), exit_status=1)
        self.assertIsNone(result.limit_reached)
        self.assertIsNone(result.native_ceiling)
        self.assertEqual(result.agent_exit, events.ABNORMAL)

    def test_35_a_ceiling_followed_by_further_activity_did_not_end_the_run(self):
        result = events.analyze(stream(
            event("max_iterations_reached", agent="researcher", max_iterations=10),
            call("a", "read_file", {"path": "src/x.py"})), exit_status=0)
        self.assertIsNone(result.limit_reached)
        self.assertIsNone(result.native_ceiling)
        self.assertEqual(result.stream, events.COMPLETE)
        self.assertEqual(result.agent_exit, events.NORMAL)

    def test_36_a_ceiling_is_never_an_infrastructure_abort_or_abnormal(self):
        result = events.analyze(stream(self.budget(), terminal=False), exit_status=137)
        self.assertNotEqual(result.agent_exit, events.ABNORMAL)
        self.assertTrue(result.ok)

    def test_37_a_host_limit_that_fired_first_outranks_a_native_ceiling(self):
        result = events.analyze(stream(self.budget()), exit_status=0,
                                host_stop={"reason": "steps"})
        self.assertEqual(result.limit_reached, "steps")
        self.assertIsNone(result.native_ceiling)
        self.assertEqual(result.stream, events.HOST_TERMINATED)
        self.assertEqual(result.agent_exit, events.HOST_LIMIT)

    def test_38_a_corrupt_stream_is_never_rescued_by_a_ceiling(self):
        result = events.analyze(stream("garbage", self.budget()), exit_status=0)
        self.assertEqual(result.stream, events.MALFORMED)
        self.assertIsNone(result.native_ceiling)



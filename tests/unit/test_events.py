    def test_18_an_unobserved_exit_status_is_abnormal(self):
        result = events.analyze(stream(call("a", "read_file")), exit_status=None)
        self.assertEqual(result.agent_exit, events.ABNORMAL)

    def test_19_no_sandbox_means_no_stream_and_no_agent(self):
        result = events.analyze("", sandbox_created=False)
        self.assertEqual(result.stream, events.NONE)
        self.assertEqual(result.agent_exit, events.NOT_STARTED)
        self.assertEqual(result.steps, 0)



"""Unit tests for the production event parser (tasks.md T039, src/dca/events.py).

Two kinds of input, deliberately:

  * the REAL captures under `gates/G11/captures/<backend>/`, recorded by gate G11 part A from the
    pinned docker_agent v1.136.0 against every available backend. They are the only evidence that
    the parser reads the runtime this repository actually pinned, and the counts asserted here are
    the ones G11's own ground truth established - markers left in the VM filesystem and read before
    anything was parsed;

  * synthetic streams for the cases a model run cannot be asked to produce on demand: native
    ceiling terminations, host-triggered stops, and the exact ordering of a repair/re-verify cycle.

The captures are never regenerated by these tests. G11 part A is accepted evidence; re-running it
would replace evidence with a fresh model run, which is the opposite of what a regression test is
for.
"""

import importlib.util
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CAPTURES = ROOT / "gates" / "G11" / "captures"


def _load(name, path):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


events = _load("dca_events", ROOT / "src" / "dca" / "events.py")


def available_backends():
    """The backends `gates/eligibility.json` records as available, so tests follow the evidence."""
    doc = json.loads((ROOT / "gates" / "eligibility.json").read_text(encoding="utf-8"))
    return sorted(name for name, backend in doc["backends"].items() if backend.get("available"))


# --- synthetic stream construction ----------------------------------------------------------------


def event(kind, **fields):
    return json.dumps({"type": kind, "agent_name": fields.pop("agent", "root"), **fields})


def call(identifier, name, arguments=None, read_only=None, kind="tool_call"):
    function = {"name": name}
    if arguments is not None:
        function["arguments"] = json.dumps(arguments)
    payload = {"tool_call": {"id": identifier, "type": "function", "function": function}}
    if read_only is not None:
        payload["tool_definition"] = {"name": name, "annotations": {"readOnlyHint": read_only}}
    return event(kind, **payload)


def response(identifier, text):
    return event("tool_call_response", tool_call_id=identifier, response=text)


def usage(session, input_tokens, output_tokens, agent="root"):
    return event("token_usage", agent=agent, session_id=session,
                 usage={"input_tokens": input_tokens, "output_tokens": output_tokens})


def partials(identifier, name, raw, pieces=3):
    """One tool call's arguments STREAMED, the way the Claude backend reports them.

    Each fragment is a slice of the JSON text, linked to the dispatched call by the same id.
    """
    size = max(1, len(raw) // pieces)
    chunks = [raw[i:i + size] for i in range(0, len(raw), size)]
    return [event("partial_tool_call",
                  tool_call={"id": identifier, "type": "function",
                             "function": {"name": name, "arguments": chunk}})
            for chunk in chunks]


def streamed_call(identifier, name, arguments):
    """The Claude shape: fragments, then a dispatched tool_call carrying NO arguments."""
    return partials(identifier, name, json.dumps(arguments)) + [
        event("tool_call", tool_call={"id": identifier, "type": "function",
                                      "function": {"name": name, "arguments": None}})]


def stream(*lines, terminal=True):
    body = list(lines)
    if terminal:
        body.append(event("stream_stopped", session_id="s", reason="normal"))
    return "\n".join([event("stream_started", session_id="s")] + body) + "\n"


# --- the real captures ----------------------------------------------------------------------------


class TestCaptures(unittest.TestCase):
    """Every assertion here restates a fact gate G11 part A already recorded as PASS."""

    def capture(self, backend, name):
        return (CAPTURES / backend / f"{name}.jsonl").read_text(encoding="utf-8")

    def test_01_three_genuine_tool_calls_count_as_exactly_three(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "count"), exit_status=0)
                self.assertEqual(result.stream, events.COMPLETE)
                self.assertEqual(result.agent_exit, events.NORMAL)
                self.assertEqual(result.steps, 3)
                self.assertEqual(result.distinct_tool_call_ids, 3)
                self.assertEqual(result.problems, [])

    def test_02_streaming_deltas_are_present_and_never_counted(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "count"), exit_status=0)
                self.assertGreater(result.event_types.get("partial_tool_call", 0), result.steps,
                                   "the capture must really contain streaming deltas")
                self.assertEqual(result.steps, result.event_types["tool_call"])

    def test_03_imitation_events_in_tool_output_add_exactly_zero_outer_events(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                text = self.capture(backend, "spoof")
                self.assertIn("tool_call", text)
                lines = [line for line in text.split("\n") if line.strip()]
                result = events.analyze(text, exit_status=0)
                self.assertEqual(result.problems, [])
                self.assertEqual(result.events, len(lines),
                                 "every outer event is a line; payload can never become one")
                self.assertEqual(result.steps, 1)

    def test_04_a_malformed_capture_is_classified_malformed_and_is_never_ok(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "malformed"), exit_status=0)
                self.assertEqual(result.stream, events.MALFORMED)
                self.assertFalse(result.ok)
                self.assertTrue(result.problems)

    def test_05_a_truncated_capture_is_classified_truncated_and_is_never_ok(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "truncated"), exit_status=0)
                self.assertEqual(result.stream, events.TRUNCATED)
                self.assertFalse(result.ok)

    def test_06_an_abruptly_killed_agent_is_abnormal_whatever_the_stream_looks_like(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "kill"), exit_status=137)
                self.assertEqual(result.agent_exit, events.ABNORMAL)
                self.assertFalse(result.ok)

    def test_07_a_complete_stream_cannot_rescue_a_non_zero_exit(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "count"), exit_status=1)
                self.assertEqual(result.stream, events.COMPLETE)
                self.assertEqual(result.agent_exit, events.ABNORMAL)

    def test_08_tokens_are_extracted_from_the_captures(self):
        for backend in available_backends():
            with self.subTest(backend=backend):
                result = events.analyze(self.capture(backend, "count"), exit_status=0)
                self.assertGreater(result.tokens, 0)
                self.assertEqual(result.token_usage["total_tokens"], result.tokens)



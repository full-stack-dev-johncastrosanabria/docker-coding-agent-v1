class TestFirstMutation(unittest.TestCase):
    CONTEXT = {"path": "/run/dca/out/context.json", "content": "{}"}

    def test_60_reads_and_inspection_are_not_mutations(self):
        result = events.analyze(stream(
            call("a", "read_file", {"path": "src/x.py"}),
            call("b", "Bash", {"command": "git status --porcelain"}),
            call("c", "Bash", {"command": "grep -rn foo src"}),
            call("d", "list_directory", {"path": "src"})), exit_status=0)
        self.assertIsNone(result.first_mutation)
        self.assertTrue(result.context_precedes_first_mutation)

    def test_61_a_scratch_only_write_before_the_first_edit_is_not_a_mutation(self):
        result = events.analyze(stream(
            call("a", "write_file", {"path": "/run/dca/out/plan.md", "content": "plan"}),
            call("b", "write_file", self.CONTEXT),
            call("c", "write_file", {"path": "src/x.py", "content": "edit"})), exit_status=0)
        self.assertEqual(result.first_mutation, 2)
        self.assertEqual(result.context_record_at, 1)
        self.assertEqual(result.plan_at, 0)
